import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import RandomForestClassifier
from sklearn.ensemble import IsolationForest

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix,
    classification_report
)

print("Libraries imported successfully!")

from google.colab import files

uploaded = files.upload()

df = pd.read_csv("creditcard.csv")

print("Dataset loaded successfully!")
print("Dataset shape:", df.shape)

df.head()

print("Dataset Information:")

df.info()

print("\nMissing Values:")
print(df.isnull().sum().sum())

print("\nTransaction Class Distribution:")
print(df["Class"].value_counts())

print("\nStatistical Summary:")
display(df.describe())

plt.figure(figsize=(6, 4))

sns.countplot(data=df, x="Class")

plt.title("Legitimate vs Fraudulent Transactions")
plt.xlabel("Transaction Class")
plt.ylabel("Number of Transactions")

plt.xticks([0, 1], ["Legitimate", "Fraudulent"])

plt.show()

plt.figure(figsize=(8, 4))

sns.histplot(
    data=df,
    x="Amount",
    hue="Class",
    bins=50,
    element="step"
)

plt.title("Transaction Amount Distribution")
plt.xlabel("Transaction Amount")
plt.ylabel("Frequency")

plt.show()

X = df.drop("Class", axis=1)

y = df["Class"]

print("Input features:", X.shape)
print("Target variable:", y.shape)

print("\nInput columns:")
print(X.columns.tolist())

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("Training data:", X_train.shape)
print("Testing data:", X_test.shape)

print("\nTraining split completed successfully!")

scaler = StandardScaler()

X_train_scaled = X_train.copy()
X_test_scaled = X_test.copy()

X_train_scaled["Amount"] = scaler.fit_transform(
    X_train[["Amount"]]
).ravel()

X_test_scaled["Amount"] = scaler.transform(
    X_test[["Amount"]]
).ravel()

print("Feature scaling completed successfully!")

lr_model = LogisticRegression(
    class_weight="balanced",
    max_iter=1000,
    random_state=42
)

lr_model.fit(X_train_scaled, y_train)

lr_predictions = lr_model.predict(X_test_scaled)

print("Logistic Regression training completed!")

rf_model = RandomForestClassifier(
    n_estimators=100,
    class_weight="balanced",
    random_state=42,
    n_jobs=-1
)

rf_model.fit(X_train, y_train)

rf_predictions = rf_model.predict(X_test)

print("Random Forest training completed!")

iso_model = IsolationForest(
    n_estimators=100,
    contamination=0.002,
    random_state=42,
    n_jobs=-1
)

iso_model.fit(X_train)

iso_raw_predictions = iso_model.predict(X_test)

iso_predictions = np.where(
    iso_raw_predictions == -1,
    1,
    0
)

print("Isolation Forest training completed!")

models = {
    "Logistic Regression": lr_predictions,
    "Random Forest": rf_predictions,
    "Isolation Forest": iso_predictions
}

results = []

for model_name, predictions in models.items():

    accuracy = accuracy_score(y_test, predictions)

    precision = precision_score(
        y_test,
        predictions,
        zero_division=0
    )

    recall = recall_score(
        y_test,
        predictions,
        zero_division=0
    )

    f1 = f1_score(
        y_test,
        predictions,
        zero_division=0
    )

    results.append({
        "Model": model_name,
        "Accuracy": round(accuracy, 4),
        "Precision": round(precision, 4),
        "Recall": round(recall, 4),
        "F1-Score": round(f1, 4)
    })

results_df = pd.DataFrame(results)

print("MODEL PERFORMANCE COMPARISON")

display(results_df)

cm = confusion_matrix(y_test, rf_predictions)

plt.figure(figsize=(6, 4))

sns.heatmap(
    cm,
    annot=True,
    fmt="d",
    cmap="Blues",
    xticklabels=["Legitimate", "Fraudulent"],
    yticklabels=["Legitimate", "Fraudulent"]
)

plt.title("Random Forest Confusion Matrix")
plt.xlabel("Predicted Class")
plt.ylabel("Actual Class")

plt.show()

sample_transaction = X_test.iloc[[0]]

prediction = rf_model.predict(sample_transaction)[0]

fraud_probability = rf_model.predict_proba(
    sample_transaction
)[0][1]

print("CREDIT CARD FRAUD DETECTION SYSTEM")
print("----------------------------------")

print("Transaction Amount:",
      sample_transaction["Amount"].iloc[0])

if prediction == 1:

    print("Prediction: Potentially Fraudulent")
    print("Risk Level: High")

else:

    print("Prediction: Likely Legitimate")
    print("Risk Level: Lower")

print("Estimated Fraud Probability:",
      round(fraud_probability * 100, 2), "%")

results_df.to_csv(
    "fraud_detection_model_results.csv",
    index=False
)

print("Model comparison report saved successfully!")

